    /**
     * 根据玩家客户端语言获取翻译文本
     * @param player 目标玩家 (可为 null，此时默认英文)
     * @param key    翻译键
     * @param args   格式化参数
     * @return 带格式的 Text 对象
     */
    public static Text translate(ServerPlayerEntity player, String key, Object... args) {
        String lang = "en_us";
        if (player != null) {
            lang = player.getClientOptions().language().toLowerCase();
        }
        Map<String, String> map;

        // 按语言代码选择映射
        if (lang.startsWith("zh_cn")) {
            map = ZH_CN;
        } else if (lang.startsWith("zh_tw") || lang.startsWith("zh_hk") || lang.startsWith("zh_mo")) {
            map = ZH_TW;
        } else if (lang.startsWith("zh")) {
            map = ZH_CN; // 其他中文变体默认简体
        } else if (lang.startsWith("ja")) {
            map = JA;
        } else if (lang.startsWith("de")) {
            map = DE;
        } else if (lang.startsWith("es")) {
            map = ES;
        } else if (lang.startsWith("it")) {
            map = IT;
        } else if (lang.startsWith("pt")) {
            map = PT;
        } else if (lang.startsWith("fr")) {
            map = FR;
        } else if (lang.startsWith("ko")) {
            map = KO;
        } else if (lang.startsWith("ru")) {
            map = RU;
        } else if (lang.startsWith("lzh")) {
            map = LZH;
        } else {
            map = EN; // 默认英文
        }

        String pattern = map.getOrDefault(key, EN.getOrDefault(key, key));
        return Text.literal(String.format(pattern, args));
    }

    /**
     * 无玩家上下文时使用 (控制台等)
     */
    public static Text translate(String key, Object... args) {
        return translate(null, key, args);
    }
